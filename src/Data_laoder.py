# -*- coding: utf-8 -*-
"""
pharmagraph.py

Builds a heterogeneous graph (HeteroData) from the PrimeKGCL knowledge graph
snapshot, and saves the processed nodes/edges/graph object for downstream use.

Original file generated by Colab:
https://colab.research.google.com/drive/1Eu391OO0gNIVJ7AwztkQobdLjOhz0SaC
"""

import os
import shutil
import pandas as pd
import torch
from torch_geometric.data import HeteroData

URL = "data/benchmark/snapshots/kg_t0.csv"
CHUNK_SIZE = 500_000


# ---------------------------------------------------------------------------
# 1. Quick preview of the raw dataset
# ---------------------------------------------------------------------------
df_preview = pd.read_csv(URL, sep=",",
                          header=0, nrows=10)
print(df_preview)


# ---------------------------------------------------------------------------
# 2. Count total rows and relation types (streamed in chunks)
# ---------------------------------------------------------------------------
total_rows = 0
relation_counts = {}

for chunk in pd.read_csv(URL, sep=",", header=0, chunksize=CHUNK_SIZE):
    total_rows += len(chunk)
    for rel, count in chunk["relation"].value_counts().items():
        relation_counts[rel] = relation_counts.get(rel, 0) + count

print("Total number of rows:", total_rows)
print("Number of different relation types:", len(relation_counts))
print(relation_counts)


# ---------------------------------------------------------------------------
# 3. Check for missing values and collect all node types
# ---------------------------------------------------------------------------
null_counts = None
node_types = set()

for chunk in pd.read_csv(URL, sep=",", header=0, chunksize=CHUNK_SIZE, dtype=str):
    chunk_nulls = chunk.isnull().sum()
    null_counts = chunk_nulls if null_counts is None else null_counts + chunk_nulls
    node_types.update(chunk["x_type"].dropna().unique())
    node_types.update(chunk["y_type"].dropna().unique())

print("Number of missing values in each column:")
print(null_counts)
print("\nNode types present:")
print(node_types)


# ---------------------------------------------------------------------------
# 4. Detect duplicate rows and self-loops
# ---------------------------------------------------------------------------
total_rows = 0
duplicate_rows = 0
self_loops = 0
key_cols = ["x_id", "x_type", "relation", "y_id", "y_type"]

for chunk in pd.read_csv(URL, sep=",", header=0, chunksize=CHUNK_SIZE, dtype=str):
    total_rows += len(chunk)
    loops = (chunk["x_id"] == chunk["y_id"]) & (chunk["x_type"] == chunk["y_type"])
    self_loops += loops.sum()
    duplicate_rows += chunk.duplicated(subset=key_cols).sum()

print("Total number of rows:", total_rows)
print("Duplicate rows (within each chunk):", duplicate_rows)
print("Self-loops:", self_loops)


# ---------------------------------------------------------------------------
# 5. Load full dataset (only needed columns) and remove duplicates
# ---------------------------------------------------------------------------
cols_needed = ["x_id", "x_type", "relation", "y_id", "y_type"]
df = pd.read_csv(URL, sep=",", header=0, dtype=str, usecols=cols_needed)
print("Dataset shape:", df.shape)

df = df.drop_duplicates(subset=key_cols)
print("Shape after removing duplicates:", df.shape)


# ---------------------------------------------------------------------------
# 6. Build a unified node table (global index across all node types)
# ---------------------------------------------------------------------------
nodes_x = df[["x_id", "x_type"]].rename(columns={"x_id": "node_id", "x_type": "node_type"})
nodes_y = df[["y_id", "y_type"]].rename(columns={"y_id": "node_id", "y_type": "node_type"})

nodes = pd.concat([nodes_x, nodes_y], ignore_index=True).drop_duplicates()
nodes = nodes.sort_values(["node_type", "node_id"]).reset_index(drop=True)
nodes["node_idx"] = nodes.index

print("Total number of unique nodes:", len(nodes))
print("\nNumber of nodes per type:")
print(nodes["node_type"].value_counts())
print("\nFirst 5 rows:")
print(nodes.head())


# ---------------------------------------------------------------------------
# 7. Map each edge's endpoints to their global node index
# ---------------------------------------------------------------------------
lookup = nodes.set_index(["node_id", "node_type"])["node_idx"]

df["x_idx"] = df.set_index(["x_id", "x_type"]).index.map(lookup).values
df["y_idx"] = df.set_index(["y_id", "y_type"]).index.map(lookup).values

missing = df["x_idx"].isnull().sum() + df["y_idx"].isnull().sum()
print("Number of edges that failed to get indexed:", missing)
print(df[["x_idx", "relation", "y_idx", "x_type", "y_type"]].head())


# ---------------------------------------------------------------------------
# 8. Save processed nodes and edges locally
# ---------------------------------------------------------------------------
os.makedirs("processed", exist_ok=True)

edges_final = df[["x_idx", "relation", "y_idx", "x_type", "y_type"]].rename(
    columns={"x_idx": "head_idx", "y_idx": "tail_idx"}
)
edges_final.to_parquet("processed/edges.parquet", index=False)

print("Saved:")
print("- processed/edges.parquet ->", len(edges_final), "rows")


# ---------------------------------------------------------------------------
# 10. Assign a per-type ("local") index needed for HeteroData
# ---------------------------------------------------------------------------
nodes_typed = nodes.copy()
nodes_typed["local_idx"] = nodes_typed.groupby("node_type").cumcount()

print(nodes_typed.head(10))
print("\nExample: First and last local index for each node type")
print(nodes_typed.groupby("node_type")["local_idx"].agg(["min", "max", "count"]))

local_lookup = nodes_typed.set_index(["node_id", "node_type"])["local_idx"]
df["x_local"] = df.set_index(["x_id", "x_type"]).index.map(local_lookup).values
df["y_local"] = df.set_index(["y_id", "y_type"]).index.map(local_lookup).values

missing = df["x_local"].isnull().sum() + df["y_local"].isnull().sum()
print("Edges that failed to get a local index:", missing)

nodes_typed.to_csv("processed/entities.csv", index=False)
print("- processed/entities.csv ->", len(nodes_typed), "rows (includes local_idx)")


# ---------------------------------------------------------------------------
# 11. Build the HeteroData graph object
# ---------------------------------------------------------------------------
data = HeteroData()

node_type_counts = nodes_typed.groupby("node_type").size().to_dict()
for ntype, count in node_type_counts.items():
    data[ntype].num_nodes = count
    data[ntype].x = torch.ones((count, 1))

for (rel, x_type, y_type), group in df.groupby(["relation", "x_type", "y_type"]):
    edge_index = torch.tensor(
        [group["x_local"].values, group["y_local"].values], dtype=torch.long
    )
    data[(x_type, rel, y_type)].edge_index = edge_index

print(data)

torch.save(data, os.path.join("processed", "pharmagraph_hetero_t0.pt"))
print("Saved: processed/pharmagraph_hetero_t0.pt")